import assert from 'node:assert/strict';
import { Readable } from 'node:stream';
import { createAiGateway, endpointUrl, isPublicAddress, normalizeItems } from './api/gateway.mjs';

const developerKey='developer-key-for-offline-check';
const userKey='user-key-for-offline-check';
const code='offline-access-code-123456';
const environment={CHRONOFLOW_STAGE:'competition',CHRONOFLOW_OFFICIAL_API_KEY:developerKey,
  CHRONOFLOW_OFFICIAL_MODEL:'offline-model',CHRONOFLOW_OFFICIAL_ACCESS_CODE:code};
const calls=[];
const transport=async(config,body)=>{calls.push({config,body});return {choices:[{message:{content:JSON.stringify({items:[{action:'create',title:'提交报告',deadline:null,minutes:60,evidence:['提交报告']}]})}}]};};
const gateway=createAiGateway({env:environment,transport});
async function call(handler,url,body,{method='POST',accessCode=code,origin='http://localhost:4173'}={}){
  const request=Readable.from(body===undefined?[]:[Buffer.from(JSON.stringify(body))]);
  request.url=url;request.method=method;request.headers={'content-type':'application/json',host:'localhost:4173',origin,'x-chronoflow-access-code':accessCode};request.socket={remoteAddress:'127.0.0.1'};
  let status,raw;
  const response={writeHead:(value)=>status=value,end:value=>raw=value};
  await handler(request,response);return {status,body:JSON.parse(raw)};
}
const publicConfig=await call(gateway,'/api/v1/ai/config',undefined,{method:'GET'});
assert.equal(publicConfig.body.defaultMode,'official');
assert.ok(!JSON.stringify(publicConfig).includes(developerKey));
assert.ok(!JSON.stringify(publicConfig).includes(code));
assert.equal((await call(gateway,'/api/v1/ai/test',{mode:'official'},{accessCode:'wrong'})).status,401);
assert.equal(calls.length,0,'An invalid access code must not spend developer quota');
const official=await call(gateway,'/api/v1/ai/test',{mode:'official',user:{apiKey:userKey}});
assert.equal(official.status,200);
assert.equal(calls.at(-1).config.apiKey,developerKey,'Official mode uses only server configuration');
const personal=await call(gateway,'/api/v1/ai/analyze',{mode:'user',user:{baseUrl:'https://provider.example/v1',model:'my-model',apiKey:userKey},input:{text:'提交报告',receivedAt:'2026-10-15T09:00:00+08:00',tasks:[]}});
assert.equal(personal.status,200);
assert.equal(calls.at(-1).config.apiKey,userKey,'User mode must not fall back to the developer key');
assert.equal(personal.body.requiresConfirmation,true);
assert.equal(personal.body.items[0].title,'提交报告');
assert.equal((await call(gateway,'/api/v1/ai/test',{mode:'user'})).status,400);
assert.equal((await call(gateway,'/api/v1/ai/test',{mode:'official'},{origin:'https://other.example'})).status,403);
const production=createAiGateway({env:{...environment,CHRONOFLOW_STAGE:'production'},transport});
assert.equal((await call(production,'/api/v1/ai/config',undefined,{method:'GET'})).body.defaultMode,'user');
assert.equal((await call(production,'/api/v1/ai/test',{mode:'official'})).status,403,'Production must reject forged official requests');
const unavailable=createAiGateway({env:{CHRONOFLOW_STAGE:'competition'},transport});
assert.equal((await call(unavailable,'/api/v1/ai/test',{mode:'official'})).status,503);
const failing=createAiGateway({env:environment,transport:async()=>{throw new Error(`internal ${developerKey}`);}});
const failure=await call(failing,'/api/v1/ai/test',{mode:'official'});
assert.equal(failure.status,500);
assert.ok(!JSON.stringify(failure).includes(developerKey),'Error bodies must not expose credentials');
const limited=createAiGateway({env:{...environment,CHRONOFLOW_OFFICIAL_REQUESTS_PER_DAY:'1'},transport});
await call(limited,'/api/v1/ai/test',{mode:'official'});
assert.equal((await call(limited,'/api/v1/ai/test',{mode:'official'})).status,429);
assert.equal(endpointUrl('https://provider.example/v1/').pathname,'/v1/chat/completions');
assert.throws(()=>endpointUrl('http://localhost:8080/v1'));
assert.throws(()=>endpointUrl('https://127.0.0.1/v1'));
assert.throws(()=>endpointUrl('https://name:password@provider.example/v1'));
for(const address of ['127.0.0.1','10.0.0.1','172.16.0.1','192.168.1.1','169.254.169.254','::1','::ffff:127.0.0.1','2001:db8::1'])assert.equal(isPublicAddress(address),false,address);
assert.equal(isPublicAddress('8.8.8.8'),true);
assert.equal(isPublicAddress('2001:4860:4860::8888'),true);
const invalidTarget=normalizeItems({items:[{action:'update',title:'延期',targetId:'other-user',evidence:['编造的依据']}]},{text:'提交报告',course:'课程',tasks:[]})[0];
assert.equal(invalidTarget.action,'manual');
assert.equal(invalidTarget.evidenceMissing,true);
assert.throws(()=>normalizeItems({items:[{action:'cancel',title:'取消报告'}]},{text:'取消报告',tasks:[]}));
console.log('Passed: API mode separation, production policy, access codes, quota, endpoint restrictions and safe analysis.');
