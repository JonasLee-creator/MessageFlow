import vm from 'node:vm';
import fs from 'node:fs';
import assert from 'node:assert/strict';

const local=new Map(),tab=new Map(),calls=[];
const storage=map=>({getItem:key=>map.get(key)||null,setItem:(key,value)=>map.set(key,String(value)),removeItem:key=>map.delete(key)});
let stage='competition';
const fetch=async(url,options)=>{
  calls.push({url,options});
  const value=url.endsWith('/config')?{stage,defaultMode:stage==='production'?'user':'official',official:{available:stage!=='production',model:'offline-model'}}:{connected:true,mode:JSON.parse(options.body).mode,model:'offline-model'};
  return {ok:true,json:async()=>value};
};
const context=vm.createContext({localStorage:storage(local),sessionStorage:storage(tab),fetch,AbortController,setTimeout,clearTimeout});
vm.runInContext(fs.readFileSync(new URL('./dist/api-client.js',import.meta.url),'utf8'),context);
const api=context.ChronoApi;
api.setScope({kind:'member',userId:'account-a'});await api.refresh();
const secret='offline-user-key-123456',code='offline-experience-code-123456';
api.save({mode:'user',baseUrl:'https://provider.example/v1',model:'my-model',apiKey:secret});
assert.equal(api.state().ready,true);
assert.ok(!JSON.stringify([...local.values()]).includes(secret),'API keys must not enter persistent preferences');
assert.ok(JSON.stringify([...tab.values()]).includes(secret),'The active tab may retain its credential');
assert.ok(!JSON.stringify(api.state()).includes(secret),'Public UI state must expose presence only');
await api.test();
assert.equal(JSON.parse(calls.at(-1).options.body).user.apiKey,secret);
api.save({mode:'official',accessCode:code});
await api.test();
const official=calls.at(-1);
assert.equal(official.options.headers['X-ChronoFlow-Access-Code'],code);
assert.equal(JSON.parse(official.options.body).mode,'official');
assert.ok(!official.options.body.includes(secret),'Official mode must not forward the user key');
assert.ok(!JSON.stringify([...local.values()]).includes(code),'Access codes must not enter persistent preferences');
api.clearCredentials();
assert.equal(api.state().hasUserKey,false);
assert.equal(api.state().hasAccessCode,false);
api.setScope({kind:'member',userId:'account-b'});
assert.equal(api.state().hasUserKey,false,'Different accounts must not inherit credentials');
stage='production';await api.refresh();
api.save({mode:'official',baseUrl:'https://provider.example/v1',model:'personal-model',apiKey:secret});
assert.equal(api.state().mode,'user','Production policy overrides a stored official preference');
await api.test();
assert.equal(JSON.parse(calls.at(-1).options.body).mode,'user');
console.log('Passed: tab-only credentials, account isolation, official payload separation and production mode.');
