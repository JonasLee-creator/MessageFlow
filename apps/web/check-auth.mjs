import vm from 'node:vm';
import fs from 'node:fs';
import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';

const source=fs.readFileSync(new URL('./dist/auth.js',import.meta.url),'utf8');
const local=new Map(),session=new Map();
const storage=map=>({getItem:key=>map.get(key)??null,setItem:(key,value)=>map.set(key,String(value)),removeItem:key=>map.delete(key)});
const context=vm.createContext({crypto:webcrypto,TextEncoder,localStorage:storage(local),sessionStorage:storage(session)});
vm.runInContext(source,context);
let auth=context.ChronoAuth;
assert.equal(auth.getSession(),null,'A new page starts at sign-in');
assert.equal(auth.guest().kind,'guest','Guest entry does not require credentials');
assert.equal(local.size,0,'Guest entry must not create an account');
auth.logout();
const password='test-password-42';
const member=await auth.register('用户甲',password,password);
assert.equal(member.kind,'member');
assert.equal(member.username,'用户甲');
const record=JSON.parse(local.get('chronoflow.accounts.v1'))[0];
assert.equal(record.verifier.length,64);
assert.ok(!local.get('chronoflow.accounts.v1').includes(password),'Passwords must not be saved in plaintext');
await assert.rejects(auth.register('用户甲',password,password),/用户名已被使用/);
await assert.rejects(auth.register('用户乙',password,'different-password'),/密码不一致/);
auth.logout();
await assert.rejects(auth.login('用户甲','wrong-password'),/用户名或密码不正确/);
assert.equal(auth.getSession(),null,'Failed sign-in must not grant a session');
await assert.rejects(auth.login('不存在',password),/用户名或密码不正确/);
const signedIn=await auth.login('用户甲',password);
assert.equal(signedIn.userId,member.userId);
vm.runInContext(source,context);
auth=context.ChronoAuth;
assert.equal(auth.getSession().userId,member.userId,'Reload preserves the active tab session');
auth.logout();
vm.runInContext(source,context);
assert.equal(context.ChronoAuth.getSession(),null,'Sign-out removes the saved session');
const unavailable=()=>{throw new Error('Storage unavailable');};
const restricted=vm.createContext({crypto:webcrypto,TextEncoder,localStorage:{getItem:unavailable,setItem:unavailable},sessionStorage:{getItem:unavailable,setItem:unavailable,removeItem:unavailable}});
vm.runInContext(source,restricted);
assert.equal(restricted.ChronoAuth.guest().kind,'guest','Guest entry remains available when storage is blocked');
console.log('Passed: guest entry, registration, password verification, duplicate names, session restore and sign-out.');
